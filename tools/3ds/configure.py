"""Generates build/3ds/build.ninja, which builds the Nintendo 3DS port as a .3dsx.

The sources are compiled in two separate worlds that must never share headers:

* Game world: the decompiled game, JSystem, nw4r and our reimplementation of the
  Wii SDK (platform/3ds/rvl). It sees the original Wii headers and is compiled to
  match the original compiler's ABI (int-sized enums, Shift-JIS string literals).
* Host world: platform/3ds/host, which talks to the 3DS through libctru and
  citro3d using the 3DS's own ABI (variable-sized enums).

The two worlds only communicate through platform/3ds/host/host.h, which uses plain
C types.

Usage: python tools/3ds/configure.py [--version RMGE01] [--devkitpro C:/devkitPro]
Then:  ninja -f build/3ds/build.ninja
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

VERSIONS = ["RMGJ01", "RMGE01", "RMGP01", "RMGK01"]

# Decompiled source trees built into the port. The Wii SDK, MSL, the runtime,
# the debugger and the Mii library are replaced by the platform layer instead.
# No GX: the game draws through Citro3D (platform/3ds/gx: the native J3D renderer and the TEV
# translation), and neither the GX/GD SDK nor a GX command interpreter is linked (block 8).
GAME_SOURCE_DIRS = ["src/Game", "src/JSystem", "src/nw4r", "platform/3ds/rvl", "platform/3ds/gx"]
HOST_SOURCE_DIRS = ["platform/3ds/host"]

# Parts of the decompiled Wii SDK that are portable as-is and reused directly.
SDK_SOURCES = ["src/RVL_SDK/os/OSMessage.c", "src/RVL_SDK/os/OSMutex.c",
    "src/RVL_SDK/mem/mem_allocator.c", "src/RVL_SDK/mem/mem_expHeap.c", "src/RVL_SDK/mem/mem_heapCommon.c", "src/RVL_SDK/mem/mem_list.c",
    # CPU-only Wii Remote speaker codecs retained for the game-side virtual audio path.
    "src/RVL_SDK/wenc/wenc.c", "src/RVL_SDK/thp/THPAudio.c",
    # The Wii's own "dummy ARAM" in MEM2, which this game uses instead of real ARAM.
    "src/RVL_SDK/aralt/aralt.c",
]

APP_TITLE = "Super Mario Galaxy"
APP_DESCRIPTION = "Unofficial 3DS port"
APP_AUTHOR = "Petari 3DS port"


def ninja_escape(path):
    return str(path).replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def quote(path):
    return f'"{path}"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", default="RMGE01", choices=VERSIONS)
    parser.add_argument("--devkitpro", default=os.environ.get("DEVKITPRO_WIN", "C:/devkitPro"))
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[2]
    os.chdir(root)

    dkp = Path(args.devkitpro)
    bin_dir = dkp / "devkitARM" / "bin"
    tools_dir = dkp / "tools" / "bin"
    version_num = VERSIONS.index(args.version)
    out = Path("build/3ds")

    # No game data is compiled in: the data files the Wii keeps inside main.dol are read from the
    # SD card at startup (platform/3ds/rvl/port_data.cpp), so the Wii build is not needed first.

    arch = "-march=armv6k -mtune=mpcore -mfloat-abi=hard -mtp=soft"
    common = f"{arch} -O2 -g -fno-math-errno -mword-relocations -ffunction-sections -fdata-sections -fno-strict-aliasing -D__3DS__"

    version_defs = " ".join([f"-D{v}={i}" for i, v in enumerate(VERSIONS)] + [f"-DVERSION={version_num}", "-DNDEBUG=1"])
    game_includes = " ".join(
        f"-I{p}"
        for p in [
            "platform/3ds/include",
            "include",
            "libs/JSystem/include",
            "libs/RVLFaceLib/include",
            "libs/RVL_SDK/include",
            "libs/Runtime/include",
            "libs/nw4r/include",
            "libs/MSL_C++/include",
            "platform/3ds/host",
        ]
    )
    game_flags = (
        f"{common} -std=gnu++14 -fno-rtti -fno-exceptions -fpermissive -w "
        "-fno-short-enums -fshort-wchar -fexec-charset=CP932 "
        # Metrowerks never reuses the stack slot of a variable whose block has ended, and the
        # game relies on it (e.g. LayoutManager keeps a pointer into such a buffer).
        "-fstack-reuse=none "
        # The game's operator new (JKRHeap) returns null when a heap is full and the code checks
        # for it (e.g. JASMemChunkPool::createNewChunk); GCC would run the constructor on null.
        "-fcheck-new "
        f"-include platform/3ds/include/msl_compat.h {version_defs} {game_includes}"
    )
    host_flags = f"{common} -Wall -I{dkp / 'libctru' / 'include'} -Iplatform/3ds/host -I{(out / 'gen').as_posix()}"

    gxx = quote(bin_dir / "arm-none-eabi-g++.exe")
    gcc = quote(bin_dir / "arm-none-eabi-gcc.exe")

    lines = [
        "# Generated by tools/3ds/configure.py; do not edit.",
        "ninja_required_version = 1.3",
        f"builddir = {ninja_escape(out)}",
        "",
        f"game_flags = {game_flags}",
        f"host_flags = {host_flags}",
        "",
        "rule cxx_game",
        f"  command = {gxx} -MMD -MF $out.d $game_flags -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CXX $in",
        "",
        "rule cc_game",
        f"  command = {gcc} -MMD -MF $out.d $game_flags -x c -std=gnu99 -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CC $in",
        "",
        "rule cxx_host",
        f"  command = {gxx} -MMD -MF $out.d $host_flags -std=gnu++17 -fno-rtti -fno-exceptions -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CXX(host) $in",
        "",
        "rule cc_host",
        f"  command = {gcc} -MMD -MF $out.d $host_flags -std=gnu11 -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CC(host) $in",
        "",
        "rule link",
        f"  command = {gxx} -specs=3dsx.specs -g {arch} -Wl,--no-enum-size-warning -Wl,--no-wchar-size-warning -Wl,--wrap=sprintf,--wrap=snprintf,--wrap=vsprintf,--wrap=vsnprintf,--wrap=__system_allocateHeaps -Wl,--gc-sections "
        f"-Wl,-Map,$map @$out.rsp -L{dkp / 'libctru' / 'lib'} -lcitro3d -lctru -lm -o $out",
        "  rspfile = $out.rsp",
        "  rspfile_content = $in",
        "  description = LINK $out",
        "",
        "rule smdh",
        f"  command = {quote(tools_dir / 'smdhtool.exe')} --create {quote(APP_TITLE)} {quote(APP_DESCRIPTION)} "
        f"{quote(APP_AUTHOR)} $in $out",
        "  description = SMDH $out",
        "",
        "rule dsx",
        f"  command = {quote(tools_dir / '3dsxtool.exe')} $in $out $smdh_option",
        "  description = 3DSX $out",
        "",
        "rule picasso",
        f"  command = {quote(tools_dir / 'picasso.exe')} -o $out $in",
        "  description = PICASSO $in",
        "",
        "rule embed",
        f"  command = {quote(sys.executable)} tools/3ds/embed.py $in $out $name",
        "  description = EMBED $in",
        "",
        "rule check3dsx",
        f"  command = {quote(sys.executable)} tools/3ds/check_3dsx.py $in $elf --stamp $out",
        "  description = CHECK $in",
        "",
    ]

    objects = []

    def add_sources(dirs, cxx_rule, cc_rule):
        for d in dirs:
            for src in sorted(Path(d).rglob("*")):
                if src.suffix not in (".cpp", ".c"):
                    continue
                obj = out / "obj" / src.with_suffix(".o")
                rule = cxx_rule if src.suffix == ".cpp" else cc_rule
                lines.append(f"build {ninja_escape(obj.as_posix())}: {rule} {ninja_escape(src.as_posix())}")
                objects.append(obj.as_posix())

    add_sources(GAME_SOURCE_DIRS, "cxx_game", "cc_game")
    for src in SDK_SOURCES:
        obj = out / "obj" / Path(src).with_suffix(".o")
        lines.append(f"build {ninja_escape(obj.as_posix())}: cc_game {ninja_escape(src)}")
        objects.append(obj.as_posix())
    # Shaders are compiled with picasso and embedded as C arrays for the host sources.
    gen = out / "gen"
    shader_headers = []
    for shader in sorted(Path("platform/3ds/host/shaders").glob("*.v.pica")):
        name = shader.name.split(".")[0] + "_shbin"
        shbin = (gen / f"{name}.shbin").as_posix()
        header = (gen / f"{name}.h").as_posix()
        lines.append(f"build {ninja_escape(shbin)}: picasso {ninja_escape(shader.as_posix())}")
        lines.append(f"build {ninja_escape(header)}: embed {ninja_escape(shbin)}")
        lines.append(f"  name = {name}")
        shader_headers.append(ninja_escape(header))

    first_host = len(lines)
    add_sources(HOST_SOURCE_DIRS, "cxx_host", "cc_host")
    for i in range(first_host, len(lines)):
        if shader_headers and lines[i].startswith("build "):
            lines[i] += " || " + " ".join(shader_headers)

    elf = (out / "smg.elf").as_posix()
    smdh = (out / "smg.smdh").as_posix()
    dsx = (out / "smg.3dsx").as_posix()
    stamp = (out / "smg.3dsx.checked").as_posix()
    lines += [
        "",
        f"build {ninja_escape(elf)}: link {' '.join(ninja_escape(o) for o in objects)}",
        f"  map = {(out / 'smg.map').as_posix()}",
    ]
    # The HOME Menu icon is Nintendo artwork kept only in the development repository
    # (platform/3ds/meta); the public one has none, and its .3dsx is made without an icon. The
    # CIA does not use this: the builder takes the icon and banner from the user's disc.
    icon = Path("platform/3ds/meta/icon.png")
    if icon.is_file():
        lines += [
            f"build {ninja_escape(smdh)}: smdh {icon.as_posix()}",
            f"build {ninja_escape(dsx)}: dsx {ninja_escape(elf)} | {ninja_escape(smdh)}",
            f"  smdh_option = --smdh={smdh}",
        ]
    else:
        lines += [f"build {ninja_escape(dsx)}: dsx {ninja_escape(elf)}", "  smdh_option ="]
    lines += [
        f"build {ninja_escape(stamp)}: check3dsx {ninja_escape(dsx)} | {ninja_escape(elf)}",
        f"  elf = {elf}",
        "",
        f"build objects: phony {' '.join(ninja_escape(o) for o in objects)}",
        f"default {ninja_escape(stamp)}",
        "",
    ]

    out.mkdir(parents=True, exist_ok=True)
    (out / "build.ninja").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out / 'build.ninja'} ({len(objects)} sources)")


if __name__ == "__main__":
    main()
